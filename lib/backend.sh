_flash_image_is_complete() {
  local image="$1"
  [[ -f "$image" && -f "${image}.build-complete" ]]
}

_flash_discover_images() {
  # During the current transition, RAM output is still a legitimate completed
  # location.  Once build publication is made canonical, remove /dev/shm here.
  local search_dirs=(
    "$PROJECT_DIR"
    "/home/image"
    "/dev/shm/steamos-build"
    "$HOME/Downloads"
  )
  [[ -n "${OUTPUT_DIR:-}" ]] && search_dirs+=("$OUTPUT_DIR")
  local d f
  local -a found=()

  for d in "${search_dirs[@]}"; do
    [[ -d "$d" ]] || continue
    while IFS="" read -r f; do
      [[ -n "$f" ]] || continue
      _flash_image_is_complete "$f" || continue
      found+=("$(readlink -f "$f")")
    done < <(find "$d" -maxdepth 1 -name '*nvidia*usbinstall*.img' -type f 2>/dev/null)
  done

  ((${#found[@]})) || return 0

  # TSV: path, location, human size, modified epoch, modified display
  local _sorted
  _sorted="$(printf '%s\n' "${found[@]}" | sort -u)"
  while IFS="" read -r f; do
    local where
    case "$f" in
      /dev/shm/*) where="RAM build" ;;
      /home/image/*) where="Persistent output" ;;
      "$PROJECT_DIR"/*) where="Project output" ;;
      *) where="Other" ;;
    esac
    printf '%s\t%s\t%s\t%s\t%s\n' \
      "$f" \
      "$where" \
      "$(du -h "$f" | cut -f1)" \
      "$(stat -c '%Y' "$f")" \
      "$(date -r "$f" '+%Y-%m-%d %H:%M:%S')"
  done <<<"$_sorted" | sort -t$'\t' -k4,4nr
}

_flash_validate_image() {
  local image="$1"
  [[ -f "$image" ]] || {
    log_error flash validation-error "Image not found: $image"
    return 1
  }

  if [[ "$(basename "$image")" == *nvidia*usbinstall*.img ]] && ! _flash_image_is_complete "$image"; then
    log_error flash validation-error "Refusing NVIDIA installer image without .build-complete marker: $image"
    return 1
  fi
}

_backend_flash() {
  [[ $EUID -eq 0 ]] || {
    log_error flash validation-error "Flash action requires root."
    exit 1
  }
  [[ "$FLASH_CONFIRMED" -eq 1 ]] || {
    log_error flash validation-error "Flash is destructive. Re-run with --confirm after the user has confirmed the target."
    exit 2
  }
  [[ -n "$IMG" ]] || {
    log_error flash validation-error "--image is required for flash"
    exit 2
  }
  [[ -n "$TARGET_DEV" ]] || {
    log_error flash validation-error "--device is required for flash"
    exit 2
  }

  IMG="$(readlink -f "$IMG")"
  _flash_validate_image "$IMG"
  [[ -b "$TARGET_DEV" ]] || {
    log_error flash validation-error "Not a block device: $TARGET_DEV"
    exit 1
  }

  if [[ "$ALLOW_SYSTEM_DISK" -ne 1 ]] && flash_is_system_disk "$TARGET_DEV"; then
    log_error flash validation-error "Refusing to flash the current system disk: $TARGET_DEV"
    log_error flash validation-error "Use --allow-system-disk only if this has been explicitly verified."
    exit 1
  fi

  # Acquire workspace-level lock to prevent concurrent operations
  if ! workspace_lock_acquire; then
    die "Another build/cleanup/flash is running — cannot proceed"
  fi
  trap 'workspace_lock_release 2>/dev/null || true' EXIT

  register_flash_pipeline
  run_pipeline || {
    log_error flash pipeline-error "Flash pipeline failed."
    exit 1
  }
}

