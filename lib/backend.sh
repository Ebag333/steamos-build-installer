_check_build_deps() {
  if [[ -f "$BACKEND_DIR/check-deps.sh" ]]; then
    bash "$BACKEND_DIR/check-deps.sh" --check-only || exit 1
    return 0
  fi

  local missing=()
  local cmd
  for cmd in losetup blkid btrfs bzip2 gzip xz pv rsync curl depmod sed awk tar zstd pacman pactree python3 readelf sgdisk sfdisk; do
    # lint-ignore: silenced-stdout — command -v output (path) is intentionally discarded; only exit code is used
    command -v "$cmd" >/dev/null || missing+=("$cmd")
  done

  if [[ ${#missing[@]} -gt 0 ]]; then
    local pkgs=()
    for cmd in "${missing[@]}"; do
      case "$cmd" in
        btrfs) pkgs+=(btrfs-progs) ;;
        readelf) pkgs+=(binutils) ;;
        depmod) pkgs+=(kmod) ;;
        pactree) pkgs+=(pacman-contrib) ;;
        sgdisk) pkgs+=(gptfdisk) ;;
        *) pkgs+=("$cmd") ;;
      esac
    done
    mapfile -t pkgs < <(printf "%s\n" "${pkgs[@]}" | sort -u)
    die "Missing host tools: ${missing[*]}. Install with: pacman -S ${pkgs[*]}"
  fi
}

_normalize_build_options() {

  [[ -z "$ROOTFS_SIZE" || "$ROOTFS_SIZE" =~ ^[0-9]+[KMGkmg]?$ ]] \
    || die "--rootfs-size takes a size like 10G, 10240M, or 10240 (plain = MiB)"

  case "$DEFAULT_SESSION" in
    "" | desktop | game) ;;
    *) die "--session must be desktop or game" ;;
  esac

  case "$WORKDIR_LOCATION" in
    auto | ram | disk) ;;
    *) die "--workdir-location must be auto, ram, or disk" ;;
  esac

  case "$UPDATE_MODE" in
    selfheal | hold | stock) ;;
    *) die "Invalid update mode: $UPDATE_MODE" ;;
  esac

  case "$BASE_OS_MODE" in
    additive | upgrade) ;;
    *) die "Invalid base OS mode: $BASE_OS_MODE" ;;
  esac

  if [[ -n "$ROOTFS_SIZE" ]]; then
    case "${ROOTFS_SIZE: -1}" in
      G | g) ROOTFS_SIZE=$((${ROOTFS_SIZE%[Gg]} * 1024)) ;;
      M | m) ROOTFS_SIZE="${ROOTFS_SIZE%[Mm]}" ;;
      K | k) ROOTFS_SIZE=$((${ROOTFS_SIZE%[Kk]} / 1024)) ;;
    esac
    ((ROOTFS_SIZE > 0)) || die "--rootfs-size must be positive"
  fi
}

_resolve_build_image() {
  if [[ -n "$IMG" ]]; then
    [[ -f "$IMG" ]] || die "Image not found: $IMG"
    IMG="$(realpath "$IMG")"
    return 0
  fi

  local -a candidates=()
  mapfile -t candidates < <(
    find "$PROJECT_DIR" -maxdepth 1 \
      \( -name '*.img' -o -name '*.img.bz2' -o -name '*.img.gz' -o -name '*.img.xz' -o -name '*.img.zst' \) \
      ! -name '*-nvidia*' | sort
  )

  case ${#candidates[@]} in
    0) die "No source image specified with --image and none was found beside the script." ;;
    1)
      IMG="$(realpath "${candidates[0]}")"
      log "Auto-detected image: $IMG"
      ;;
    *) die "Multiple source images found; pass one explicitly with --image." ;;
  esac
}

_backend_build() {
  [[ $EUID -eq 0 ]] || die "Build action requires root."

  _load_build_libs

  # Initialize structured logging.
  mkdir -p "/home/.steamos-build/logs/${BUILD_ID}"
  local _console_level="info"
  if ((DEBUG)); then
    _console_level="debug"
  elif ((VERBOSE)); then
    _console_level="debug"
  fi

  log_init \
    --log-file "/home/.steamos-build/logs/${BUILD_ID}/run.jsonl" \
    --console-level "$_console_level"

  # ── Failure context functions ────────────────────────────────────────────
  _build_failure_journal_context() {
    printf "img='%s' kver='%s' step='%s'\n" \
      "$(basename "${IMG:-unknown}")" \
      "${KVER:-unknown}" \
      "${CURRENT_STEP:-unknown}"
  }

  _build_failure_snapshot_extra() {
    # ── Build configuration ──────────────────────────────────────────────
    log_debug build failure-snapshot "BUILD CONFIGURATION"
    log_info build failure-config \
      "Build config" \
      img "${IMG:-unknown}" \
      out "${OUT:-unknown}" \
      workdir "${WORKDIR:-unknown}" \
      rootfs_size "${ROOTFS_SIZE:-unknown}" \
      kver "${KVER:-unknown}" \
      base_os_mode "${BASE_OS_MODE:-unknown}" \
      update_mode "${UPDATE_MODE:-unknown}" || true

    # ── Workspace disk space ─────────────────────────────────────────────
    log_debug build failure-snapshot "WORKSPACE DISK SPACE"
    if [[ -n "${WORKDIR:-}" ]]; then
      df -h "$WORKDIR" 2>&1 | log_capture_stream build debug workspace-disk || true
      du -sh "$WORKDIR" 2>&1 | log_capture_stream build debug workspace-usage || true
    fi

    # ── Source image info ────────────────────────────────────────────────
    log_debug build failure-snapshot "SOURCE IMAGE"
    if [[ -n "${IMG:-}" && -e "${IMG:-}" ]]; then
      # shellcheck disable=SC2012  # diagnostic output, not parsed
      ls -lh "$IMG" 2>&1 | log_capture_stream build debug source-image || true
    fi
    lsblk 2>&1 | log_capture_stream build debug block-devices || true

    # ── Rootfs mount state ───────────────────────────────────────────────
    if [[ -n "${MNT:-}" ]] && mountpoint -q "$MNT" 2>/dev/null; then
      log_debug build failure-snapshot "ROOTFS MOUNT STATE"
      findmnt "$MNT" 2>&1 | log_capture_stream build debug rootfs-mount || true
      btrfs filesystem usage "$MNT" 2>&1 | log_capture_stream build debug rootfs-usage || true
      df -h "$MNT" 2>&1 | log_capture_stream build debug rootfs-disk || true
    fi

    # ── Overlay state ────────────────────────────────────────────────────
    if [[ -n "${MERGED:-}" ]] && mountpoint -q "$MERGED" 2>/dev/null; then
      log_debug build failure-snapshot "OVERLAY STATE"
      findmnt "$MERGED" 2>&1 | log_capture_stream build debug overlay-mount || true
      df -h "$MERGED" 2>&1 | log_capture_stream build debug overlay-disk || true
    fi

    # ── Package state ────────────────────────────────────────────────────
    local _hw_new_pkgs_file="${WORKDIR:-}/hw-new-pkgs.txt"
    if [[ -n "${WORKDIR:-}" && -f "$_hw_new_pkgs_file" ]]; then
      log_debug build failure-snapshot "PACKAGE STATE"
      local _total _new _removed
      _total="$(wc -l <"$_hw_new_pkgs_file" 2>/dev/null || echo 0)"
      _new="$(grep -c '^+' "$_hw_new_pkgs_file" 2>/dev/null || echo 0)"
      _removed="$(grep -c '^-[^-]' "$_hw_new_pkgs_file" 2>/dev/null || echo 0)"
      log_info build failure-packages \
        "Package counts" \
        total "$_total" \
        new "$_new" \
        removed "$_removed" || true
      head -20 "$_hw_new_pkgs_file" 2>&1 | log_capture_stream build debug package-list || true
    fi

    # ── Driver state ─────────────────────────────────────────────────────
    if [[ -n "${MERGED:-}" ]] && mountpoint -q "$MERGED" 2>/dev/null \
      && [[ -n "${KVER:-}" ]]; then
      log_debug build failure-snapshot "DRIVER STATE"
      chroot "$MERGED" dkms status 2>&1 | log_capture_stream build debug driver-dkms || true
      chroot "$MERGED" pacman -Q nvidia-utils 2>&1 | log_capture_stream build debug driver-nvidia-utils || true
    fi
  }

  failure_journal_context() { _build_failure_journal_context; }    # lint-ignore: no-shadow
  failure_snapshot_extra() { _build_failure_snapshot_extra "$@"; } # lint-ignore: no-shadow

  _normalize_build_options
  _resolve_build_image
  _check_build_deps

  [[ "$(basename "$IMG")" != *-nvidia* ]] \
    || die "Input looks like an already-patched image — start from the clean repair image."

  IMG_BASE="${IMG%.bz2}"
  IMG_BASE="${IMG_BASE%.gz}"
  IMG_BASE="${IMG_BASE%.xz}"
  IMG_BASE="${IMG_BASE%.zst}"

  local out_basename="${IMG_BASE%.img}-nvidia-usbinstall.img"
  out_basename="$(basename "$out_basename")"

  # Output directory: explicit OUTPUT_DIR, or same directory as source image.
  if [[ -n "${OUTPUT_DIR:-}" ]]; then
    mkdir -p "$OUTPUT_DIR"
    OUT_FINAL="$OUTPUT_DIR/$out_basename"
  else
    OUT_FINAL="$(dirname "$IMG_BASE")/$out_basename"
  fi
  OUT="${OUT_FINAL}.building"

  [[ -n "$WORKDIR" ]] || WORKDIR="$(dirname "$OUT")/.nvidia-usb-work"

  # shellcheck disable=SC2034
  LOOPDEV=""
  local _trap_rc
  local _cleanup_done=0
  mkdir -p /home/.steamos-build/logs
  # shellcheck disable=SC2154  # _remaining is declared inside trap string
  trap '_trap_rc=$?; trap - EXIT; set +e; log_close 2>/dev/null || true; if [[ "${_cleanup_done:-0}" -eq 0 ]]; then
  if ! cleanup_check_host_namespace; then
    warn "EXIT trap: init namespace detected — refusing unsafe cleanup"
    warn "  Build may have lost its namespace; manual cleanup may be required"
    _trap_rc=1
  else
    cleanup_stop_background_jobs
    cleanup_remove_udev_rules
    persist_debug_logs 2>/dev/null || true
    _trap_cleanup_rc=0
    overlay_cleanup 2>/dev/null || _trap_cleanup_rc=1
    cleanup_environment 2>/dev/null || _trap_cleanup_rc=1
    if ((_trap_cleanup_rc != 0)); then
      warn "EXIT trap: cleanup failed — workspace may need manual cleanup"
      _trap_rc=1
    fi
    _remaining=""
    _remaining="$(findmnt -rno TARGET,SOURCE,FSTYPE 2>/dev/null | grep -v "^/dev\|^proc\|^sys\|^run\|^tmp\|^home\|^root\|^opt\|^nix\|^srv\|^efi\|^esp" | grep -v "^-")"
    if [[ -n "$_remaining" ]]; then
      warn "Remaining mounts after cleanup:"
      warn "$_remaining"
    fi
  fi
fi; workspace_lock_release 2>/dev/null || true; exit "$_trap_rc"' EXIT

  : "${UPSTREAM_DRIVER_REF:=master}"
  # shellcheck disable=SC2034
  UPSTREAM_DRIVER_SRC_BASE="https://raw.githubusercontent.com/torvalds/linux/$UPSTREAM_DRIVER_REF/drivers/hid"

  # Log mount namespace proof — verifies unshare isolation is active.
  log_info system mount_namespace "Build mount namespace: $(readlink /proc/self/ns/mnt 2>/dev/null || echo '<unknown>')"
  log_info system mount_propagation "Root mount propagation: $(findmnt -no PROPAGATION / 2>/dev/null || echo '<unknown>')"

  log_info build start "Starting steamos-build build (rootfs=${ROOTFS_SIZE:-5120}M)"

  # Acquire workspace-level lock to prevent concurrent operations
  if ! workspace_lock_acquire; then
    die "Another build/cleanup/flash is running — cannot proceed"
  fi

  # Ledger: recover from previous run, then initialize
  # shellcheck disable=SC2119  # pipeline_recover uses default state_root
  pipeline_recover || warn "Ledger recovery failed — proceeding without crash recovery"
  pipeline_init "" "$WORKDIR" || warn "Ledger initialization failed — proceeding without crash recovery"

  # Register and run the build pipeline
  register_build_pipeline
  if ! run_pipeline; then
    die "Build pipeline failed"
  fi
}

# ---------------------------------------------------------------------------
# Validate backend — image mounting and cleanup
# ---------------------------------------------------------------------------

VALIDATE_MNT=""
VALIDATE_LOOP=""
VALIDATE_ROOTFS=""
VALIDATE_VARPART=""
VALIDATE_UDEV_RULE="/run/udev/rules.d/89-steamos-validate.rules"

_validate_mount_image() {
  local img="$1"

  # Install udev guard BEFORE attaching loop — prevents udisks2 from
  # seeing the partitions and triggering an automount popup.
  mkdir -p /run/udev/rules.d
  cat "$(heredoc_dir)/static/validate-udev.rule" >"$VALIDATE_UDEV_RULE"
  run_dangerous_cmd udevadm control --reload-rules
  log "Installed udev guard: $VALIDATE_UDEV_RULE"

  log "Attaching loop device: $img"
  VALIDATE_LOOP="$(losetup -f --show --partscan "$img")" \
    || die "Failed to attach loop device"
  cleanup_track_loop "$VALIDATE_LOOP" "$img" "validate image"
  log "  Loop: $VALIDATE_LOOP"
  run_dangerous_cmd udevadm settle --timeout=10

  log "Scanning partitions on $VALIDATE_LOOP"
  local part label
  for part in "$VALIDATE_LOOP"p*; do
    label="$(blkid -s PARTLABEL -o value "$part" 2>/dev/null)" || continue
    log "  $part: ${label:-<unknown>}"
    case "$label" in
      rootfs-A | rootfs) VALIDATE_ROOTFS="$part" ;;
      var-A | var) VALIDATE_VARPART="$part" ;;
    esac
  done

  [[ -n "$VALIDATE_ROOTFS" ]] || die "No rootfs partition found in $img"
  log "  rootfs: $VALIDATE_ROOTFS"
  log "  var:    ${VALIDATE_VARPART:-<not found>}"

  log "Mounting $VALIDATE_ROOTFS on $VALIDATE_MNT (read-only)"
  cleanup_set_workspace "$VALIDATE_MNT" 2>/dev/null || true
  cleanup_track_tempdir "$VALIDATE_MNT" "validate workspace" || true
  cleanup_mount "$VALIDATE_MNT" "validate rootfs" -- -o ro "$VALIDATE_ROOTFS" \
    || die "Failed to mount rootfs"

  # Mount var if it exists as a separate partition.
  # Recovery images may have var baked into rootfs; skip if not found.
  if [[ -n "$VALIDATE_VARPART" ]]; then
    mkdir -p "$VALIDATE_MNT/var"
    log "Mounting $VALIDATE_VARPART on $VALIDATE_MNT/var (read-only)"
    cleanup_mount "$VALIDATE_MNT/var" "validate var" -- -o ro "$VALIDATE_VARPART" \
      || die "Failed to mount var"
  fi

  log "Mount complete"
}

_validate_cleanup() {
  local _had_e=0
  [[ -o errexit ]] && _had_e=1
  set +e
  # Unmount all tracked mounts in reverse order (var before rootfs-A)
  cleanup_unmount_registered 2>/dev/null || true
  if [[ -n "${VALIDATE_LOOP:-}" ]]; then
    strict_detach_loop "$VALIDATE_LOOP"
  fi
  if declare -F cleanup_verify >/dev/null 2>&1; then
    cleanup_verify || warn "Validate cleanup: verification detected issues"
  fi
  [[ -d "$VALIDATE_MNT" ]] && rmdir "$VALIDATE_MNT" 2>/dev/null
  # Remove udev guard and reload
  if [[ -n "${VALIDATE_UDEV_RULE:-}" ]]; then
    log "_validate_cleanup: removing udev rule $VALIDATE_UDEV_RULE"
    rm -f "$VALIDATE_UDEV_RULE" 2>/dev/null
    log "_validate_cleanup: reloading host udev rules (udevadm control --reload-rules)"
    if ! run_dangerous_cmd udevadm control --reload-rules 2>/dev/null; then
      warn "_validate_cleanup: udevadm control --reload-rules failed"
    fi
  else
    log_debug pipeline cleanup "_validate_cleanup: VALIDATE_UDEV_RULE is unset; skipping udev cleanup"
  fi
  [[ "$_had_e" -eq 1 ]] && set -e
}

_backend_validate() {
  # shellcheck source=lib/library-loader.sh
  source "$BACKEND_DIR/library-loader.sh"
  load_workflow_libs "validate" "$BACKEND_DIR"

  # Source the validate pipeline
  # shellcheck source=lib/pipelines/pipeline_validate.sh
  source "$BACKEND_DIR/pipelines/pipeline_validate.sh"

  # Pass config via environment for the pipeline to read
  export VALIDATE_CONFIG="${CONFIG_FILE:-}"

  if [[ -n "$IMG" ]]; then
    # ── Offline image validation ──────────────────────────────────────
    [[ $EUID -eq 0 ]] || die "Image validation requires root (needed for loop/mount)."
    [[ -f "$IMG" ]] || die "Image not found: $IMG"
    IMG="$(readlink -f "$IMG")"

    VALIDATE_MNT="$(mktemp -d /tmp/steamos-validate.XXXXXX)"

    trap '_validate_cleanup' EXIT

    log "=== Mounts before ==="
    local _loop_state
    _loop_state="$(losetup -a 2>/dev/null)" || true
    if [[ -n "$_loop_state" ]]; then
      log "$_loop_state"
    else
      log "  (no active loop devices)"
    fi

    _validate_mount_image "$IMG"

    export VALIDATE_ROOT="$VALIDATE_MNT"
    export MERGED="$VALIDATE_MNT"
    export OPT_MODE="chroot"
    export OPT_ROOT="$VALIDATE_MNT"

    log " "
    log "╔═══════════════════════════════════════════════════════════╗"
    log "║  VALIDATING OFFLINE IMAGE                                ║"
    log "╠═══════════════════════════════════════════════════════════╣"
    log "║  Image:    $IMG"
    log "║  Rootfs:   $VALIDATE_ROOTFS"
    log "║  Var:      ${VALIDATE_VARPART:-<not separate>}"
    log "║  Mount:    $VALIDATE_MNT"
    log "║  Mode:     chroot"
    log "╚═══════════════════════════════════════════════════════════╝"
    log " "
  else
    # ── Live system validation ────────────────────────────────────────
    export VALIDATE_ROOT="${VALIDATE_ROOT:-/}"

    log " "
    log "╔═══════════════════════════════════════════════════════════╗"
    log "║  VALIDATING LIVE SYSTEM                                  ║"
    log "╠═══════════════════════════════════════════════════════════╣"
    log "║  Root:     $VALIDATE_ROOT"
    log "║  Mode:     live"
    log "╚═══════════════════════════════════════════════════════════╝"
    log " "
  fi

  # Initialize structured logging.
  mkdir -p "/home/.steamos-build/logs/${BUILD_ID}"
  local _console_level="info"
  if ((DEBUG)); then
    _console_level="debug"
  elif ((VERBOSE)); then
    _console_level="debug"
  fi

  log_init \
    --log-file "/home/.steamos-build/logs/${BUILD_ID}/validate.jsonl" \
    --console-level "$_console_level"

  register_validate_pipeline
  local rc=0
  run_pipeline || rc=$?

  # Run cleanup before reporting final state
  if [[ -n "$VALIDATE_MNT" ]]; then
    _validate_cleanup
    trap - EXIT
  fi

  if [[ -n "$VALIDATE_MNT" ]]; then
    log " "
    log "=== Mounts after ==="
    local _loop_after
    _loop_after="$(losetup -a 2>/dev/null)" || true
    if [[ -n "$_loop_after" ]]; then
      log "$_loop_after"
    else
      log "  (no active loop devices)"
    fi
  fi

  return "$rc"
}

