_backend_cleanup() {
  [[ $EUID -eq 0 ]] || die "Cleanup action requires root."

  # shellcheck source=lib/common.sh
  source "$BACKEND_DIR/common.sh"
  # shellcheck source=lib/protected.sh
  source "$BACKEND_DIR/protected.sh"
  # shellcheck source=lib/mounts.sh
  source "$BACKEND_DIR/mounts.sh"
  # shellcheck source=lib/pipeline_init.sh
  source "$BACKEND_DIR/pipeline_init.sh"

  # Initialize structured logging for cleanup
  mkdir -p "/home/.steamos-build/logs/${BUILD_ID}" 2>/dev/null || true
  local _console_level="info"
  if ((DEBUG)); then
    _console_level="debug"
  elif ((VERBOSE)); then
    _console_level="debug"
  fi

  log_init \
    --log-file "/home/.steamos-build/logs/${BUILD_ID}/cleanup.jsonl" \
    --console-level "$_console_level"

  local state_root="${HOME}/.steamos-build/ledger"
  local run_id="${CLEANUP_RUN_ID:-}"
  local purge="${CLEANUP_PURGE:-0}"

  ensure_steamos_build_dirs

  # If --run-id specified, clean only that run
  if [[ -n "$run_id" ]]; then
    local run_dir="$state_root/runs/$run_id"
    [[ -d "$run_dir" ]] || die "Run not found: $run_id"
    [[ -f "$run_dir/manifest" ]] || die "Run has no manifest: $run_id"

    local run_state
    run_state="$(grep -m1 '^run_state' "$run_dir/manifest" 2>/dev/null | cut -f2)" || run_state=""

    log "Cleaning run $run_id (state=$run_state)"

    case "$run_state" in
      ACTIVE | RECOVERING | BLOCKED)
        # If the build process is still alive, enter its mount namespace
        # to perform cleanup where the mounts are actually visible.
        if cleanup_ledger_pid_alive "$run_dir/manifest"; then
          if cleanup_enter_build_namespace "$run_dir/manifest"; then
            log "Run $run_id cleaned via namespace entry"
            log "Cleanup complete: 1 cleaned, 0 failed, 0 already clean"
            return 0
          else
            warn "Run $run_id: namespace cleanup failed — build alive but nsenter failed"
            warn "  Manual cleanup may be required"
            log "Cleanup complete: 0 cleaned, 1 failed, 0 already clean"
            return 1
          fi
        fi
        # Build process is dead — proceed with init-namespace recovery
        if cleanup_recover "$run_dir"; then
          log "Run $run_id cleaned successfully"
          log "Cleanup complete: 1 cleaned, 0 failed, 0 already clean"
          return 0
        else
          warn "Run $run_id cleanup incomplete — some resources may still be in use"
          log "Cleanup complete: 0 cleaned, 1 failed, 0 already clean"
          return 1
        fi
        ;;
      CLEAN)
        log "Run $run_id is already CLEAN"
        safe_rmdir "$run_dir" 2>/dev/null || true
        log "Removed CLEAN run directory"
        ;;
      *)
        warn "Unknown run state: $run_state"
        ;;
    esac
    log "Cleanup complete: 0 cleaned, 0 failed, 0 already clean"
    return 0
  fi

  # No --run-id: clean ALL stale runs
  if [[ ! -d "$state_root/runs" ]]; then
    log "No runs directory found — nothing to clean"
    return 0
  fi

  # --- Pre-cleanup state report ---
  local report_total=0 report_active=0 report_recovering=0 report_blocked=0 report_clean=0 report_corrupt=0
  local run_dir
  for run_dir in "$state_root/runs"/*/; do
    [[ -d "$run_dir" ]] || continue
    ((++report_total)) || true
    local manifest="$run_dir/manifest"
    if [[ ! -f "$manifest" ]]; then
      ((++report_corrupt)) || true
      continue
    fi
    local _rs
    _rs="$(grep -m1 '^run_state' "$manifest" 2>/dev/null | cut -f2)" || _rs=""
    case "$_rs" in
      ACTIVE) ((++report_active)) || true ;;
      RECOVERING) ((++report_recovering)) || true ;;
      BLOCKED) ((++report_blocked)) || true ;;
      CLEAN) ((++report_clean)) || true ;;
      *) ((++report_corrupt)) || true ;;
    esac
  done

  log " "
  log "=== State Report ==="
  log "  $report_total run(s) found"
  ((report_active)) && log "    $report_active    ACTIVE"
  ((report_recovering)) && log "    $report_recovering    RECOVERING"
  ((report_blocked)) && log "    $report_blocked    BLOCKED"
  ((report_clean)) && log "    $report_clean    CLEAN"
  ((report_corrupt)) && log "    $report_corrupt    CORRUPT/UNKNOWN"
  log " "
  log_debug cleanup run-state "Detailed run state:"
  for run_dir in "$state_root/runs"/*/; do
    [[ -d "$run_dir" ]] || continue
    cleanup_report_run_state "$run_dir"
  done
  log " "

  # --- Proceed with cleanup ---
  local cleaned=0 failed=0 already_clean=0

  for run_dir in "$state_root/runs"/*/; do
    [[ -d "$run_dir" ]] || continue

    local manifest="$run_dir/manifest"
    [[ -f "$manifest" ]] || continue

    local rid
    rid="$(basename "$run_dir")"

    local run_state
    run_state="$(grep -m1 '^run_state' "$manifest" 2>/dev/null | cut -f2)" || run_state=""

    case "$run_state" in
      ACTIVE | RECOVERING | BLOCKED)
        log "Cleaning stale run $rid (state=$run_state)..."
        # If the build process is still alive, enter its mount namespace
        # to perform cleanup where the mounts are actually visible.
        if cleanup_ledger_pid_alive "$manifest"; then
          if cleanup_enter_build_namespace "$manifest"; then
            log "  Run $rid cleaned via namespace entry"
            ((++cleaned)) || true
          else
            warn "  Run $rid: namespace cleanup failed — build alive but nsenter failed"
            warn "    Manual cleanup may be required"
            ((++failed)) || true
          fi
        elif cleanup_recover "$run_dir"; then
          log "  Run $rid cleaned"
          ((++cleaned)) || true
        else
          warn "  Run $rid cleanup incomplete"
          ((++failed)) || true
        fi
        ;;
      CLEAN)
        debug "Run $rid is already CLEAN"
        ((++already_clean)) || true
        if ((purge)); then
          safe_rmdir "$run_dir" 2>/dev/null || true
          debug "  Purged CLEAN run $rid"
        fi
        ;;
      *)
        warn "Run $rid has unknown state: $run_state"
        ;;
    esac
  done

  # --- Post-cleanup state report ---
  log " "
  log_debug cleanup run-state "Detailed run state (post-cleanup):"
  for run_dir in "$state_root/runs"/*/; do
    [[ -d "$run_dir" ]] || continue
    cleanup_report_run_state "$run_dir"
  done

  log " "
  log "Cleanup complete: $cleaned cleaned, $failed failed, $already_clean already clean"

  if ((failed > 0)); then
    return 1
  fi
  return 0
}

_backend_rebuild() {
  [[ $EUID -eq 0 ]] || die "Rebuild action requires root."

  # ── Persistent log setup (must happen before sourcing common.sh) ────────
  PERSIST_LOG_DIR="/home/.steamos-build/logs"
  mkdir -p "$PERSIST_LOG_DIR"

  local run_id
  run_id="$(date +%Y%m%d-%H%M%S)-$$"
  # shellcheck disable=SC2034  # used by failure_snapshot_extra via RUN_LOG
  RUN_LOG="$PERSIST_LOG_DIR/repatch-$run_id.log"

  ln -sfn "$(basename "$RUN_LOG")" \
    "$PERSIST_LOG_DIR/repatch-latest.log"

  # Keep stdout/stderr flowing to the caller, but independently retain
  # everything on the persistent /home filesystem.
  # Save original fds so tee can write to the real console.
  exec 7>&1 8>&2
  exec > >(tee -a "$RUN_LOG" >&7) 2>&1 # lint-ignore: tee-redirect

  # ── Repatch-specific globals (must be set before sourcing common.sh) ────
  # shellcheck disable=SC2034  # read by sourced common.sh
  LOG_TAG="repatch"
  # shellcheck disable=SC2034  # read by sourced common.sh
  LOGGER_TAG="steamos-build-repatch"
  # shellcheck disable=SC2034  # read by sourced common.sh
  LOG_COLOR=0
  CURRENT_STEP="startup"
  # shellcheck disable=SC2034  # read by sourced common.sh
  FAILURE_REPORTED=0

  # May not exist yet if failure happens very early.
  : "${NEWROOT:=}"

  # ── Source libraries ─────────────────────────────────────────────────────
  _load_rebuild_libs
  ensure_steamos_build_dirs

  # ── Failure context functions ────────────────────────────────────────────
  _rebuild_failure_journal_context() {
    printf "partset='%s' kver='%s'\n" \
      "${PARTSET:-unknown}" \
      "${KVER:-unknown}"
  }

  _rebuild_failure_snapshot_extra() {
    local _slot

    # Send a desktop notification to the user about the critical failure.
    _notify_desktop critical \
      "SteamOS update patch failed" \
      "The SteamOS update was cancelled because a critical customization failed.

Failed step: ${CURRENT_STEP:-unknown}

Log: ${RUN_LOG:-unknown}"

    log_debug repatch failure-snapshot "SLOT STATE"
    rauc status --detailed 2>&1 | log_capture_stream repatch debug slot-state || true
    steamos-bootconf list-images 2>&1 | log_capture_stream repatch debug slot-state || true

    for _slot in A B; do
      log_debug repatch failure-snapshot "Slot $_slot config"
      steamos-bootconf --image "$_slot" config \
        --get boot-attempts \
        --get boot-requested-at \
        --get image-invalid \
        --get comment 2>&1 | log_capture_stream repatch debug "slot-$_slot-config" || true
    done

    if [[ -n "${NEWROOT:-}" ]] && mountpoint -q "$NEWROOT" 2>/dev/null; then
      log_debug repatch failure-snapshot "TARGET ROOTFS"
      findmnt "$NEWROOT" 2>&1 | log_capture_stream repatch debug target-rootfs || true
      btrfs filesystem usage "$NEWROOT" 2>&1 | log_capture_stream repatch debug target-rootfs || true

      if [[ -n "${KVER:-}" ]]; then
        log_debug repatch failure-snapshot "TARGET DRIVER STATE"
        chroot "$NEWROOT" dkms status 2>&1 | log_capture_stream repatch debug target-driver-state || true
        chroot "$NEWROOT" pacman -Q nvidia-utils 2>&1 | log_capture_stream repatch debug target-driver-state || true
      fi
    fi
  }

  failure_journal_context() { _rebuild_failure_journal_context; }    # lint-ignore: no-shadow
  failure_snapshot_extra() { _rebuild_failure_snapshot_extra "$@"; } # lint-ignore: no-shadow

  # _notify_desktop URGENCY TITLE BODY
  #   Send a desktop notification to the deck user's Plasma session.
  #   Urgency: "critical" (sticky), "normal" (auto-expires), "low".
  #   Falls back through: notify-send → busctl → log only.
  _notify_desktop() {
    local urgency="${1:-normal}"
    local title="$2"
    local body="$3"

    local user="deck"
    local uid

    uid="$(id -u "$user" 2>/dev/null)" || {
      log "_notify_desktop: cannot resolve uid for $user"
      return 1
    }

    [[ -S "/run/user/$uid/bus" ]] || {
      log "_notify_desktop: no D-Bus session for $user (no /run/user/$uid/bus)"
      return 1
    }

    local icon="dialog-information"
    [[ "$urgency" == "critical" ]] && icon="dialog-error"

    # Prefer notify-send if available.
    if command -v notify-send >/dev/null 2>&1; then
      runuser -u "$user" -- env \
        XDG_RUNTIME_DIR="/run/user/$uid" \
        DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/$uid/bus" \
        notify-send \
        --urgency="$urgency" \
        --app-name="SteamOS NVIDIA Patcher" \
        --icon="$icon" \
        "$title" \
        "$body" 2>/dev/null && return 0

      log "_notify_desktop: notify-send failed, falling back to busctl"
    fi

    # Fallback: direct D-Bus call via busctl (part of systemd, always present).
    local urgency_byte=1
    [[ "$urgency" == "critical" ]] && urgency_byte=2
    [[ "$urgency" == "low" ]] && urgency_byte=0

    runuser -u "$user" -- env \
      XDG_RUNTIME_DIR="/run/user/$uid" \
      DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/$uid/bus" \
      busctl --user call \
      org.freedesktop.Notifications \
      /org/freedesktop/Notifications \
      org.freedesktop.Notifications \
      Notify \
      "susssasa{sv}" \
      "SteamOS NVIDIA Patcher" \
      0 \
      "$icon" \
      "$title" \
      "$body" \
      0 \
      1 "urgency" "y" "$urgency_byte" \
      2>/dev/null && return 0

    log "_notify_desktop: busctl fallback also failed"
    return 1
  }

  # ── Resolve PARTSET ─────────────────────────────────────────────────────
  PARTSET="${PARTSET:-other}"

  # ── Safety guard: refuse to modify the booted slot ──────────────────────
  local _booted _target_slot
  _booted="$(steamos-bootconf this-image 2>/dev/null || true)"
  _target_slot=""
  case "$PARTSET" in
    other)
      case "$_booted" in
        A) _target_slot=B ;;
        B) _target_slot=A ;;
      esac
      ;;
    A | B) _target_slot="$PARTSET" ;;
  esac

  if [[ -n "$_booted" && -n "$_target_slot" && "$_target_slot" == "$_booted" ]]; then
    die "Refusing to modify the currently booted slot ($_booted). Use 'other' or specify the inactive slot."
  fi

  log "Repatch target: partset=$PARTSET booted=${_booted:-unknown} target=${_target_slot:-unknown}"

  # ── Workspace setup ─────────────────────────────────────────────────────
  # shellcheck disable=SC2034  # read by sourced pipeline_rebuild.sh
  ROOTDEV="/dev/disk/by-partsets/$PARTSET/rootfs"
  # shellcheck disable=SC2034  # read by sourced pipeline_rebuild.sh
  EFIDEV="/dev/disk/by-partsets/$PARTSET/efi"

  NEWROOT="$(mktemp -d /tmp/repatch-root.XXXXXX)"
  # SteamOS /home is ext4 with casefold enabled, which OverlayFS rejects as an
  # upperdir.  Build inside a temporary plain-ext4 loopback filesystem stored on
  # /home, where there is enough space for DKMS/toolchain work.
  # shellcheck disable=SC2034  # read by sourced pipeline_rebuild.sh
  WORKIMG=/home/.steamos-build-work.img
  # shellcheck disable=SC2034  # read by sourced pipeline_rebuild.sh
  WORK="$(mktemp -d /tmp/repatch-work.XXXXXX)"
  # shellcheck disable=SC2034  # read by sourced pipeline_rebuild.sh
  WORK_LOOPDEV=""

  cleanup_set_workspace "$NEWROOT" 2>/dev/null || true

  # ── Register and run pipeline ───────────────────────────────────────────
  register_rebuild_pipeline
  register_rebuild_cleanup

  # Chain tee flush into the EXIT trap that register_rebuild_cleanup just set.
  # Without this, the tee subprocess would be orphaned on exit.
  local _existing_exit_trap
  _existing_exit_trap="$(trap -p EXIT | sed "s/^trap -- '//;s/' EXIT$//")"
  # shellcheck disable=SC2064  # intentional: expand _existing_exit_trap at set-time for trap chaining
  trap "${_existing_exit_trap:+$_existing_exit_trap; }exec 1>&7 2>&8 7>&- 8>&-; wait" EXIT

  # Ledger: recover from previous run, then initialize
  # shellcheck disable=SC2119  # pipeline_recover uses default state_root
  pipeline_recover || warn "Ledger recovery failed — proceeding without crash recovery"
  pipeline_init "" "/home/.steamos-build" || warn "Ledger initialization failed — proceeding without crash recovery"

  # Run the pipeline
  if run_pipeline; then
    # Pipeline succeeded — summarize results
    local _ok_count=0 _fail_count=0 _skip_count=0
    for _entry in "${PATCH_RESULTS[@]}"; do
      local _name _status _detail
      IFS='|' read -r _name _status _detail <<<"$_entry"
      if [[ "$_status" == "ok" ]]; then
        ((++_ok_count)) || true
      elif [[ "$_status" == "skip" ]]; then
        ((++_skip_count)) || true
      else
        ((++_fail_count)) || true
      fi
    done

    if ((_fail_count == 0)); then
      step "OK — $PARTSET is NVIDIA-ready (${KVER:-unknown})"
      exit 0
    fi

    # Some optional patches failed but slot is bootable
    warn ""
    warn "============================================================"
    warn " SteamOS NVIDIA Repatch: COMPLETED WITH WARNINGS"
    warn "============================================================"
    warn ""
    warn "SteamOS update installed successfully, but some optional"
    warn "patches failed.  The updated slot remains bootable."
    warn ""
    local _warn_failed_list=""
    warn "Patch results:"
    for _entry in "${PATCH_RESULTS[@]}"; do
      local _name _status _detail
      IFS='|' read -r _name _status _detail <<<"$_entry"
      if [[ "$_status" == "ok" ]]; then
        warn "  ✓ $_name"
      elif [[ "$_status" == "skip" ]]; then
        warn "  ○ $_name — skipped: $_detail"
      else
        warn "  ✗ $_name — $_detail"
        _warn_failed_list+="$_name, "
      fi
    done
    _warn_failed_list="${_warn_failed_list%, }"
    warn ""
    warn "Full log: $RUN_LOG"
    warn "============================================================"
    warn ""

    _notify_desktop normal \
      "SteamOS NVIDIA: patch warnings" \
      "The SteamOS update succeeded, but some optional patches failed: $_warn_failed_list.

Your system is bootable. See the repatch log for details:
$RUN_LOG"

    exit 10
  else
    # Pipeline failed — critical failure
    warn ""
    warn "============================================================"
    warn " SteamOS NVIDIA Repatch: CRITICAL FAILURE"
    warn "============================================================"
    warn ""
    warn "A critical customization failed. The staged OS update has been"
    warn "cancelled to prevent an unbootable system."
    warn ""
    warn "Full log: $RUN_LOG"
    warn "============================================================"
    warn ""

    _notify_desktop critical \
      "SteamOS NVIDIA: patch failed" \
      "The SteamOS update was cancelled because a critical customization failed.

Your system is unchanged. See the repatch log for details:
$RUN_LOG"

    exit 1
  fi
}

