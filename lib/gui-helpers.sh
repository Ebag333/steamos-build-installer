# ---- dependency check ----
gui_check_deps() {
  local missing=()
  for cmd in yad lsblk python3; do
    command -v "$cmd" >/dev/null || missing+=("$cmd")
  done
  if [[ ${#missing[@]} -gt 0 ]]; then
    yad --text="Missing required tools: ${missing[*]}" --button="OK:0" 2>/dev/null
    return 1
  fi
}

# ---- image scanning ----

# Scan for existing SteamOS images in common locations.
# Prints one path per line, sorted by modification time (newest first).
gui_scan_images() {
  local script_dir="${1:-.}"
  local search_dirs=(
    "$script_dir"
    "$script_dir/.nvidia-usb-work"
    "/dev/shm/nvidia-build"
    "$HOME/Downloads"
    "$HOME/Downloads/.nvidia-usb-work"
    "/tmp"
  )
  local imgs=()
  for d in "${search_dirs[@]}"; do
    [[ -d "$d" ]] || continue
    while IFS= read -r f; do
      imgs+=("$f")
    done < <(find "$d" -maxdepth 1 \( \
      -name '*.img' -o -name '*.img.bz2' -o -name '*.img.gz' \
      -o -name '*.img.xz' -o -name '*.img.zst' \
    \) -type f \
      ! -name '*.building' \
      ! -name 'overlay-work.img' \
      ! -name 'rootfs-writable.img' \
      ! -name '*-nvidia-usbinstall.img.building' \
      2>/dev/null)
  done
  printf '%s\n' "${imgs[@]}" | sort -u
}

# Get human-readable image info: "filename (size)"
gui_image_info() {
  local img="$1"
  local size
  size="$(du -h "$img" 2>/dev/null | cut -f1)"
  echo "$(basename "$img") ($size)"
}

# ---- config I/O ----

# Write a config file from current variables.
#   gui_write_config PATH
gui_write_config() {
  local conf="$1"
  cat > "$conf" <<EOF
# steamos-nvidia-installer config — generated by gui.sh
IMG="$IMG"
DRIVER_SPEC="$DRIVER_SPEC"
UPDATE_MODE="$UPDATE_MODE"
ADD_INSTALLER=$ADD_INSTALLER
TRIM_CUDA=$TRIM_CUDA
BUILD_HW_SUPPORT=$BUILD_HW_SUPPORT
THUNDERBOLT=$THUNDERBOLT
DEFAULT_SESSION="$DEFAULT_SESSION"
ROOTFS_SIZE="$ROOTFS_SIZE"
SKIP_SIG=$SKIP_SIG
FIX_KEYRING=$FIX_KEYRING
WORKDIR="$WORKDIR"
WORKDIR_LOCATION="$WORKDIR_LOCATION"
EOF
}

# Read a config file (source it).
#   gui_read_config PATH
gui_read_config() {
  local conf="$1"
  [[ -f "$conf" ]] || { echo "Config not found: $conf" >&2; return 1; }
  source "$conf"
}

# ---- YAD dialog wrappers ----

# Simple info dialog
gui_info() {
  local title="$1" text="$2"
  yad --title="$title" --text="$text" --button="OK:0" --width=500 2>/dev/null
}

# Simple error dialog
gui_error() {
  local text="$1"
  yad --title="Error" --text="<b>Error:</b>\n\n$text" --button="OK:0" --width=400 2>/dev/null
}

# Simple warning dialog
gui_warning() {
  local title="$1" text="$2"
  yad --title="$title" --text="<b>Warning:</b>\n\n$text" --button="OK:0" --width=500 2>/dev/null
}

# Question dialog.  Returns 0 for OK, 1 for Cancel.
gui_question() {
  local title="$1" text="$2" ok_label="${3:-OK}" cancel_label="${4:-Cancel}"
  yad --title="$title" --text="$text" \
    --button="$cancel_label:1" --button="$ok_label:0" \
    --width=500 2>/dev/null
}

# Mode selection dialog.  Sets GUI_MODE to "build" or "flash".
gui_mode_dialog() {
  local has_images="$1"
  local text="<b>SteamOS NVIDIA Installer</b>\n\n"
  text+="What would you like to do?"

  if [[ "$has_images" == "yes" ]]; then
    text+="\n\n<i>Existing images were found in common locations.</i>"
  fi

  GUI_MODE="$(yad --list --title="SteamOS NVIDIA Installer" \
    --text="$text" \
    --column="Action" --column="Description" \
    --width=450 --height=300 \
    --print-column=1 \
    build "Build a new SteamOS NVIDIA image" \
    flash "Flash an existing image to USB" \
    quit "Exit" \
  2>/dev/null)" || GUI_MODE="quit"

  # YAD appends a trailing pipe
  GUI_MODE="${GUI_MODE%|}"
}

