# Flash image selector dialog.  Sets FLASH_IMG.
gui_flash_select_image() {
  local script_dir="$1"
  shift
  local images=("$@")

  if [[ ${#images[@]} -eq 0 ]]; then
    # No auto-detected images — use file chooser
    FLASH_IMG="$(yad --file --title="Select Image" \
      --text="No images auto-detected.  Select a SteamOS image file." \
      --file-filter="Images (*.img *.img.bz2 *.img.gz *.img.xz *.img.zst) | *.img *.img.bz2 *.img.gz *.img.xz *.img.zst" \
      --width=600 \
    2>/dev/null)" || return 1
    FLASH_IMG="${FLASH_IMG%|}"
  elif [[ ${#images[@]} -eq 1 ]]; then
    FLASH_IMG="${images[0]}"
  else
    # Multiple images — let user pick
    local list_args=()
    for img in "${images[@]}"; do
      list_args+=("$(gui_image_info "$img")" "$img")
    done
    FLASH_IMG="$(yad --list --title="Select Image" \
      --text="Multiple images found.  Select one to flash." \
      --column="Image" --column="Path" \
      --width=700 --height=400 \
      --print-column=2 \
      --selectable-rows \
      "${list_args[@]}" \
    2>/dev/null)" || return 1
    FLASH_IMG="${FLASH_IMG%|}"
  fi

  [[ -n "$FLASH_IMG" && -f "$FLASH_IMG" ]] || return 1
}

# Flash device selector dialog.  Sets FLASH_DEV.
gui_flash_select_device() {
  local device_list
  device_list="$(flash_scan_devices)"

  [[ -n "$device_list" ]] || {
    gui_error "No USB devices found.\n\nPlug in a USB stick and try again."
    return 1
  }

  local rows=()
  while IFS=$'\t' read -r dev size tran model tag; do
    local type_label="Internal"
    [[ "$tag" == "[removable]" ]] && type_label="Removable"
    rows+=("$dev" "$size" "$model" "$tran" "$type_label")
  done <<< "$device_list"

  local img_info
  img_info="$(gui_image_info "$FLASH_IMG")"

  FLASH_DEV="$(yad --list \
    --title="Select Target Device" \
    --text="Select the target USB device.\n\nImage: $img_info\n\n<b>ALL DATA ON THE SELECTED DEVICE WILL BE DESTROYED.</b>" \
    --column="Device" --column="Size" --column="Model" --column="Bus" --column="Type" \
    --width=750 --height=400 \
    --print-column=1 \
    --selectable-rows \
    "${rows[@]}" \
  2>/dev/null)" || return 1
  FLASH_DEV="${FLASH_DEV%|}"
  FLASH_DEV="$(echo "$FLASH_DEV" | tr -d ' ')"

  [[ -n "$FLASH_DEV" && -b "$FLASH_DEV" ]] || return 1
}

# Flash confirmation dialog.  Returns 0 to proceed.
gui_flash_confirm() {
  local img_info dev_size
  img_info="$(gui_image_info "$FLASH_IMG")"
  dev_size="$(flash_device_size "$FLASH_DEV")"

  # Check for system disk
  if flash_is_system_disk "$FLASH_DEV"; then
    gui_warning "Warning: System Disk" \
      "<b>$FLASH_DEV appears to be the disk you are running from.</b>\n\nIf this is your recovery USB, the OS is loaded into RAM so flashing is safe.\n\nIf this is your internal drive, <b>DO NOT proceed</b>."
    return 1
  fi

  gui_question "Confirm Flash" \
    "<b>About to flash:</b>\n\n  $img_info\n\n<b>To:</b>\n\n  $FLASH_DEV ($dev_size)\n\n<b>This PERMANENTLY DESTROYS all data on $FLASH_DEV.</b>\n\nThis cannot be undone." \
    "Flash" "Cancel"
}

# Build confirmation dialog.  Returns 0 to proceed.
gui_build_confirm() {
  local update_desc
  case "$UPDATE_MODE" in
    selfheal) update_desc="Self-healing (recommended)" ;;
    hold)     update_desc="Hold updates" ;;
    stock)    update_desc="Stock (driver removed on update)" ;;
  esac

  gui_question "Confirm Build" \
    "<b>Build configuration:</b>\n\n  Source: $(basename "$IMG")\n  Driver: $DRIVER_SPEC\n  Updates: $update_desc\n  Installer: $([ "$ADD_INSTALLER" -eq 1 ] && echo yes || echo no)\n  Trim CUDA: $([ "$TRIM_CUDA" -eq 1 ] && echo yes || echo no)\n  HW Support: $([ "$BUILD_HW_SUPPORT" -eq 1 ] && echo yes || echo no)\n  Rootfs: ${ROOTFS_SIZE} MB\n  Build Location: $WORKDIR_LOCATION\n\n<b>This will build a new SteamOS NVIDIA image.</b>" \
    "Build" "Cancel"
}

# Progress log window.  Tails a log file in real time.
#   gui_progress_log TITLE LOGFILE [PID]
gui_progress_log() {
  local title="$1" logfile="$2" pid="${3:-}"

  if [[ -n "$pid" ]]; then
    # Tail the log and watch for the process to finish
    ( tail -f "$logfile" 2>/dev/null &
      TAIL_PID=$!
      wait "$pid" 2>/dev/null
      kill "$TAIL_PID" 2>/dev/null
    ) | yad --text-info --title="$title" \
        --width=800 --height=500 \
        --fontname="monospace" \
        --wrap --tail \
        --button="Close:0" \
        --tail 2>/dev/null
  else
    yad --text-info --title="$title" \
      --width=800 --height=500 \
      --fontname="monospace" \
      --wrap --tail \
      --button="Close:0" \
      < "$logfile" 2>/dev/null
  fi
}

# Success dialog.
gui_done() {
  local title="$1" msg="$2"
  yad --title="$title" --text="$msg" --button="OK:0" --width=500 2>/dev/null
}
